List<String> get staticProvinces => staticLocationData.keys.toList()..sort();

List<String> citiesForProvince(String? province) {
  final cities = staticLocationData[province]?.keys.toList() ?? <String>[];
  cities.sort();
  return cities;
}

List<String> barangaysForCity(String? province, String? city) {
  final barangays = staticLocationData[province]?[city]?.toList() ?? <String>[];
  barangays.sort();
  return barangays;
}
